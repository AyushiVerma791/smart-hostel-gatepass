def generate_svg_avatar(name, file_path, color_pair):
    """Generate a clean SVG avatar with student initials and professional styling."""
    bg_color, fg_color = color_pair
    parts = name.split()
    initials = "".join(p[0].upper() for p in parts[:2]) if parts else "ST"
    
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">
  <rect width="100" height="100" rx="50" fill="{bg_color}" />
  <circle cx="50" cy="50" r="46" fill="none" stroke="rgba(255,255,255,0.2)" stroke-width="2" />
  <text x="50" y="58" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif" 
        font-size="34" font-weight="700" fill="{fg_color}" text-anchor="middle" dominant-baseline="middle">
    {initials}
  </text>
</svg>"""
    os.makedirs(os.path.dirname(file_path), exist_ok=True)
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(svg)

