    guard_pwd_hash = generate_password_hash("guard123")

    with get_db_connection(db_path) as conn:
        cursor = conn.cursor()
        
        # Clean existing data
        cursor.execute("DELETE FROM gate_logs")
        cursor.execute("DELETE FROM notifications")
        cursor.execute("DELETE FROM outpasses")
        cursor.execute("DELETE FROM users")
        
